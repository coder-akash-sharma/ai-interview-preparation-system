const mongoose = require("mongoose");

// ==========================================
// ANSWER EVALUATION SCHEMA
// ==========================================

const answerSchema = new mongoose.Schema(
  {
    // Interview question
    question: {
      type: String,
      required: true,
      trim: true,
    },

    // Candidate's submitted answer
    answer: {
      type: String,
      required: true,
      trim: true,
    },

    // AI evaluation score for this answer
    score: {
      type: Number,
      min: 0,
      max: 10,
      default: null,
    },

    // AI evaluation status
    status: {
      type: String,
      enum: [
        "correct",
        "partially-correct",
        "incorrect",
        "not-evaluated",
      ],
      default: "not-evaluated",
    },

    // Feedback generated by AI
    feedback: {
      type: String,
      default: "",
      trim: true,
    },

    // Suggested or improved answer
    suggestedAnswer: {
      type: String,
      default: "",
      trim: true,
    },

    // Concepts the candidate missed
    missingConcepts: {
      type: [String],
      default: [],
    },

    // Evaluation status helps distinguish failed AI evaluations
    evaluationStatus: {
      type: String,
      enum: ["pending", "completed", "failed"],
      default: "pending",
    },
  },
  {
    _id: false,
  }
);

// ==========================================
// INTERVIEW SCHEMA
// ==========================================

const interviewSchema = new mongoose.Schema(
  {
    // User who completed the interview
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    // Selected interview role
    role: {
      type: String,
      required: true,
      trim: true,
    },

    // Selected difficulty
    difficulty: {
      type: String,
      required: true,
      enum: ["Easy", "Medium", "Hard"],
    },

    // Questions, submitted answers, and evaluations
    answers: {
      type: [answerSchema],
      default: [],
    },

    // Overall score out of 100
    score: {
      type: Number,
      min: 0,
      max: 100,
      default: null,
    },

    // Overall interview evaluation
    evaluation: {
      type: String,
      enum: ["pending", "completed", "failed"],
      default: "pending",
    },

    // Interview strengths
    strengths: {
      type: [String],
      default: [],
    },

    // Areas that need improvement
    weaknesses: {
      type: [String],
      default: [],
    },

    // Personalized recommendations
    suggestions: {
      type: [String],
      default: [],
    },

    // Overall AI-generated summary
    summary: {
      type: String,
      default: "",
      trim: true,
    },

    // Interview status
    status: {
      type: String,
      enum: ["completed", "in-progress"],
      default: "in-progress",
    },
  },
  {
    timestamps: true,
  }
);

// ==========================================
// EXPORT MODEL
// ==========================================

module.exports = mongoose.model("Interview", interviewSchema);